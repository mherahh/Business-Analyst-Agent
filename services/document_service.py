"""Document generation service for Word (.docx) and Markdown (.md) deliverables.

Creates professional business analysis artifacts with styled headings, metadata,
structured tables, bullet lists, and parallel Markdown exports.
"""
from __future__ import annotations

import os
from typing import Any
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from config.settings import OUTPUT_DIR


def _apply_docx_styling(doc: Document) -> None:
    """Configures default styles for a clean, professional typography palette."""
    # Normal body style
    style_normal = doc.styles["Normal"]
    style_normal.font.name = "Calibri"
    style_normal.font.size = Pt(11)
    style_normal.font.color.rgb = RGBColor(0x22, 0x22, 0x22)


def save_markdown_doc(filename: str, title: str, sections: list[tuple[str, Any]], output_dir: str | None = None) -> str:
    """Creates a clean, readable Markdown version of the document."""
    target_dir = output_dir or OUTPUT_DIR
    os.makedirs(target_dir, exist_ok=True)
    if not filename.endswith(".md"):
        filename = os.path.splitext(filename)[0] + ".md"
    path = os.path.join(target_dir, filename)

    lines = [f"# {title}", ""]
    for heading, content in sections:
        lines.append(f"## {heading}")
        lines.append("")
        if isinstance(content, list):
            for item in content:
                if isinstance(item, dict):
                    # Formatted key-value or table row
                    row_parts = [f"**{k}**: {v}" for k, v in item.items() if v]
                    lines.append(f"- {' | '.join(row_parts)}")
                else:
                    lines.append(f"- {item}")
        elif isinstance(content, dict):
            for k, v in content.items():
                lines.append(f"- **{k}**: {v}")
        else:
            lines.append(str(content))
        lines.append("")

    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines).strip() + "\n")
    return path


def save_doc(
    filename: str,
    title: str,
    sections: list[tuple[str, Any]],
    output_dir: str | None = None,
    save_markdown: bool = True,
) -> str:
    """Create a styled Word (.docx) document and optionally a Markdown (.md) twin.

    Args:
        filename: Base filename (e.g. 'requirement_analysis.docx').
        title: Main document title.
        sections: List of (heading, content) tuples.
        output_dir: Directory where files will be saved.
        save_markdown: Whether to simultaneously export an accompanying .md file.

    Returns:
        Path to the primary .docx document.
    """
    target_dir = output_dir or OUTPUT_DIR
    os.makedirs(target_dir, exist_ok=True)

    if not filename.endswith(".docx"):
        filename = os.path.splitext(filename)[0] + ".docx"
    docx_path = os.path.join(target_dir, filename)

    doc = Document()
    _apply_docx_styling(doc)

    # Document Header / Title
    title_p = doc.add_heading(level=0)
    title_run = title_p.add_run(title)
    title_run.font.name = "Calibri"
    title_run.font.size = Pt(24)
    title_run.font.bold = True
    title_run.font.color.rgb = RGBColor(0x1E, 0x3A, 0x8A)  # Navy Blue accent

    # Subtitle / metadata stamp
    sub_p = doc.add_paragraph("Business Analysis Specification Deliverable | Generated by Business Analyst Agent")
    sub_p.paragraph_format.space_after = Pt(18)
    sub_run = sub_p.runs[0]
    sub_run.font.italic = True
    sub_run.font.size = Pt(9.5)
    sub_run.font.color.rgb = RGBColor(0x66, 0x66, 0x66)

    # Sections
    for heading, content in sections:
        h = doc.add_heading(heading, level=1)
        h.paragraph_format.space_before = Pt(14)
        h.paragraph_format.space_after = Pt(6)

        if isinstance(content, list):
            for item in content:
                if isinstance(item, dict):
                    # Render structured dictionary items nicely
                    p = doc.add_paragraph(style="List Bullet")
                    for idx, (k, v) in enumerate(item.items()):
                        k_run = p.add_run(f"{k.capitalize()}: ")
                        k_run.bold = True
                        p.add_run(f"{v}" + (" | " if idx < len(item) - 1 else ""))
                else:
                    doc.add_paragraph(str(item), style="List Bullet")
        elif isinstance(content, dict):
            for k, v in content.items():
                p = doc.add_paragraph(style="List Bullet")
                p.add_run(f"{k}: ").bold = True
                p.add_run(str(v))
        else:
            p = doc.add_paragraph(str(content))
            p.paragraph_format.space_after = Pt(6)

    doc.save(docx_path)

    # Also save Markdown version if requested
    if save_markdown:
        md_name = os.path.splitext(filename)[0] + ".md"
        save_markdown_doc(md_name, title, sections, output_dir=target_dir)

    return docx_path
